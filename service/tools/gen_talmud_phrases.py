"""Writes src/talmud_phrases.h from talmud_phrases.txt.

    python gen_talmud_phrases.py

talmud_phrases.txt: the common 2-4 word Aramaic phrases of the Bavli, one per
line, tab, count (the same list as tool/voice_pack/talmud_phrases.txt in
Otzaria). The second pass (voice::PhraseRescorer) tries them at the end of each
segment.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "talmud_phrases.h")

phrases = [l.split("\t")[0] for l in open(os.path.join(HERE, "talmud_phrases.txt"), encoding="utf-8").read().splitlines() if l.strip()]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_talmud_phrases.py — do not edit.\n")
    f.write("// Common Aramaic phrases of the Bavli (2-4 words), most frequent first.\n")
    f.write("#pragma once\n\n#include <string>\n#include <vector>\n\nnamespace voice {\n\n")
    f.write("inline const std::vector<std::string>& talmudPhrases() {\n")
    f.write("  static const std::vector<std::string> list = {\n")
    for p in phrases:
        f.write(f'      "{p}",\n')
    f.write("  };\n  return list;\n}\n\n}  // namespace voice\n")
print(len(phrases), "phrases")
